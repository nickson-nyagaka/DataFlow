    lines.append("# INDICATOR DICTIONARY — DATAFLOW\n")
    lines.append(
        "Complete indicator and column specifications for DATAFLOW, extracted directly from executable code in `reference/OPTIMIZED_DATA_MGT.sanitized.ipynb`.\n"
    )
    lines.append(
        "Audit date: 2026-11-10 | Author: DATAFLOW Engineering Agent | Phase: 0\n"
    )
    lines.append("\n---\n")
    lines.append("## 1. Indicator Schema Overview\n")
    lines.append(
        "Per Master Brief §8, every output column generated by `.agg(...)`, summary merges, or export blocks is formally defined below.\n"
    )
    lines.append("\n---\n")
    lines.append("## 2. Semester Logic by Indicator Family\n")
    lines.append(
        "As identified in Lead L-15, semester logic differs substantially across indicators. The table below documents the exact semester logic implemented in the notebook.\n"
    )
    lines.append(
        "| Indicator Family | Output Column(s) | Logic Type | Semester Definition | Legacy Quirks / Notes |"
    )
    lines.append("|---|---|---|---|---|")
    for s in semester_table:
        fam = s["indicator_family"]
        cols = f"`{s['output_columns']}`"
        ltype = s["logic_type"]
        logic = f"`{s['period_logic']}`"
        notes = s["notes"].replace("|", "\\|")
        lines.append(f"| {fam} | {cols} | {ltype} | {logic} | {notes} |")

    lines.append("\n---\n")
    lines.append("## 3. Full Output Column Dictionary\n")
    lines.append(f"Total defined output columns: {len(indicators)}.\n")

    for ind in indicators:
        lines.append(f"### `{ind['output_column']}` ({ind['label']})\n")
        lines.append(f"- **Stable ID:** `{ind['id']}`")
        lines.append(f"- **Excel Label:** `{ind['label']}`")
        lines.append(f"- **Populations:** {ind['populations']}")
        lines.append(f"- **Grain:** `{ind['grain']}`")
        lines.append(f"- **Source Columns:** `{ind['source_columns']}`")
        lines.append(f"- **Source Values:** `{ind['source_values']}`")
        lines.append(f"- **Period Logic:** {ind['period_logic']}")
        lines.append(
            f"- **Propagation (`any_in_unique_allrows`):** {ind['propagation']}"
        )
        lines.append(f"- **Aggregation:** `{ind['aggregation']}`")
        lines.append(f"- **Notebook Reference:** {ind['notebook_ref']}")
        lines.append(f"- **Legacy Quirks:** {ind['legacy_quirks']}")
        lines.append(f"- **Status:** `{ind['status']}`")
        lines.append("\n")

    return "\n".join(lines)


